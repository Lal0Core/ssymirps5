#!/usr/bin/env python3
"""Generate ps5_rune_tables.h: FreeBSD _RuneLocale tables for the "C" locale (ASCII)."""
import sys
A, C, D, G, L, P, S, U, X, B, R, N = (0x100, 0x200, 0x400, 0x800, 0x1000, 0x2000, 0x4000,
                                      0x8000, 0x10000, 0x20000, 0x40000, 0x400000)
SW1 = 0x40000000
types, lower, upper = [], [], []
for c in range(256):
    t = 0
    if c < 128:
        ch = chr(c)
        if ch.isalpha(): t |= A
        if c < 32 or c == 127: t |= C
        if ch.isdigit(): t |= D | N
        if 33 <= c <= 126: t |= G
        if 'a' <= ch <= 'z': t |= L
        if 'A' <= ch <= 'Z': t |= U
        if 33 <= c <= 126 and not ch.isalnum(): t |= P
        if ch in ' \t\n\v\f\r': t |= S
        if ch in '0123456789abcdefABCDEF': t |= X
        if ch in ' \t': t |= B
        if 32 <= c <= 126: t |= R | SW1
        # FreeBSD keeps a digit's value in the low byte (digittoint).
        if ch.isdigit(): t |= c - ord('0')
        elif ch in 'abcdef': t |= c - ord('a') + 10
        elif ch in 'ABCDEF': t |= c - ord('A') + 10
    types.append(t)
    lower.append(c + 32 if 65 <= c <= 90 else c)
    upper.append(c - 32 if 97 <= c <= 122 else c)
def arr(name, vals, fmt):
    rows = [', '.join(fmt(v) for v in vals[i:i + 8]) for i in range(0, 256, 8)]
    return f'#define {name} \\\n    ' + ', \\\n    '.join(rows) + '\n'
out = ['/* Generated by gen/make_rune_tables.py; do not edit. */\n',
       arr('PS5_C_RUNETYPE', types, lambda v: f'0x{v:08x}UL'),
       arr('PS5_C_MAPLOWER', lower, str), arr('PS5_C_MAPUPPER', upper, str)]
sys.stdout.write('\n'.join(out))
